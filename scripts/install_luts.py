"""Copy Fiji/ImageJ LUT files into the user LUT folder (~/.scopi/luts) so Scopi lists them.

    python scripts/install_luts.py references/fiji/luts

Fiji is GPL; the LUTs are data files that stay on this machine (they are not bundled with Scopi).
Fire/Grays/Ice/Spectrum are built into ImageJ itself and are regenerated by Scopi instead.
"""

import shutil
import sys
from pathlib import Path

from scopi.core.luts import load_lut, user_lut_dir


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    src, dst = Path(sys.argv[1]), user_lut_dir()
    dst.mkdir(parents=True, exist_ok=True)
    n = 0
    for p in sorted(src.iterdir()):
        if p.suffix.lower() not in (".lut", ".txt") or p.name.lower() == "readme.txt":
            continue
        try:
            load_lut(p)
        except ValueError:
            print(f"skipped (unrecognised format): {p.name}")
            continue
        shutil.copy2(p, dst / p.name)
        n += 1
    print(f"installed {n} LUTs into {dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
